"""Regenerate committed golden files. Explicit recipe, no test-time magic.

Run from the repo root after a deliberate schema or exemplar change::

    uv run python tests/make_goldens.py

Writes tests/golden/ir/<name>.json (canonical bytes) and schema/ir-v1.json.
Review the diff before committing — these files are the IR contract.
"""

import json
import shutil
import subprocess
from pathlib import Path

from greater_tables import (
    TableDoc, build, canonical_json, render_text, render_tikz,
)
from greater_tables.render.css import write_asset

from exemplars import EXEMPLARS
from registry import fixtures

ROOT = Path(__file__).parent.parent


def main() -> None:
    golden_ir = ROOT / 'tests' / 'golden' / 'ir'
    golden_text = ROOT / 'tests' / 'golden' / 'text'
    golden_tikz = ROOT / 'tests' / 'golden' / 'tikz'
    for d in (golden_ir, golden_text, golden_tikz):
        d.mkdir(parents=True, exist_ok=True)

    for name, make in EXEMPLARS.items():
        doc = make()
        (golden_ir / f'{name}.json').write_bytes(canonical_json(doc))
        (golden_tikz / f'{name}.tex').write_text(
            render_tikz(doc), encoding='utf-8', newline='\n')
        print(f'wrote {name}.json + {name}.tex')

    for name, (data, spec) in fixtures().items():
        doc = build(data, spec)
        (golden_ir / f'fx-{name}.json').write_bytes(canonical_json(doc))
        (golden_text / f'{name}.txt').write_text(
            render_text(doc), encoding='utf-8', newline='\n')
        (golden_tikz / f'fx-{name}.tex').write_text(
            render_tikz(doc), encoding='utf-8', newline='\n')
        print(f'wrote fx-{name} ir + text + tikz')

    schema_path = ROOT / 'schema' / 'ir-v1.json'
    schema = TableDoc.model_json_schema()
    schema_path.write_text(json.dumps(schema, indent=2, sort_keys=True) + '\n',
                           encoding='utf-8')
    print(f'wrote {schema_path}')

    print(f'wrote {write_asset()}')

    node = shutil.which('node')
    if node:
        subprocess.run([node, str(ROOT / 'js' / 'build.mjs')],
                       check=True, cwd=ROOT)
        subprocess.run([node, str(ROOT / 'js' / 'transcript.mjs'), '--write'],
                       check=True, cwd=ROOT)
    else:
        print('node not found — walker dist and transcripts not regenerated')

    print(f'wrote {write_demo()}')
    print(f'wrote {write_demo2()}')


def write_demo() -> Path:
    """Self-contained demo gallery: every golden IR rendered by the walker.

    Embeds gt.css, the iife walker build, and each IR JSON — double-click
    the file, no server needed. Regenerated here so it can never go stale.
    """
    assets = ROOT / 'src' / 'greater_tables' / 'assets'
    iife = (assets / 'gt-render.iife.js').read_text(encoding='utf-8')
    sheet = (assets / 'gt.css').read_text(encoding='utf-8')
    sections = []
    for f in sorted((ROOT / 'tests' / 'golden' / 'ir').glob('*.json')):
        payload = f.read_text(encoding='utf-8').replace('</', r'<\/')
        sections.append(
            f'<section>\n<h2>{f.stem}</h2>\n'
            f'<script type="application/json" class="gt-doc">{payload}</script>\n'
            '<div class="host"></div>\n</section>')
    page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>greater_tables — golden fixture gallery</title>
<style>
:root {{ color-scheme: light dark; }}
body {{ font-family: system-ui, sans-serif; max-width: 70em;
       margin: 2em auto; padding: 0 1em; }}
h1 {{ font-size: 1.3em; }} h2 {{ font-size: 1em; opacity: 0.7;
       margin: 2.2em 0 0.5em; font-family: monospace; }}
{sheet}
</style>
<script>{iife}</script>
</head>
<body>
<h1>greater_tables — golden fixture gallery</h1>
<p>Every committed golden IR document, rendered client-side by
<code>gt-render.iife.js</code> with the committed <code>gt.css</code>.
Regenerated by <code>tests/make_goldens.py</code>.</p>
{chr(10).join(sections)}
<script>
document.querySelectorAll('script.gt-doc').forEach(s => {{
    const doc = JSON.parse(s.textContent);
    GtRender.renderTable(doc, {{ mount: s.nextElementSibling, allowHtml: true }});
}});
</script>
</body>
</html>
'''
    path = ROOT / 'demo.html'
    path.write_text(page, encoding='utf-8', newline='\n')
    return path


