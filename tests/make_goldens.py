def write_demo2() -> Path:
    """Curated showcase: TeX, wrapping (both generators), eng format, solver."""
    assets = ROOT / 'src' / 'greater_tables' / 'assets'
    iife = (assets / 'gt-render.iife.js').read_text(encoding='utf-8')
    sheet = (assets / 'gt.css').read_text(encoding='utf-8')
    sections = []
    for name, title, blurb, fit, width in _DEMO2:
        payload = (ROOT / 'tests' / 'golden' / 'ir' / f'{name}.json') \
            .read_text(encoding='utf-8').replace('</', r'<\/')
        attrs = f' data-fit="{fit}"' if fit else ''
        attrs += f' data-width="{width}"' if width else ''
        sections.append(
            f'<section>\n<h2>{title}</h2>\n<p>{blurb}</p>\n'
            f'<script type="application/json" class="gt-doc"{attrs}>'
            f'{payload}</script>\n<div class="host"></div>\n</section>')
    page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>greater_tables — demo 2: TeX, wrapping, eng format, width solver</title>
<style>
:root {{ color-scheme: light dark; }}
body {{ font-family: system-ui, sans-serif; max-width: 70em;
       margin: 2em auto; padding: 0 1em; }}
h1 {{ font-size: 1.3em; }} h2 {{ font-size: 1.05em; margin: 2.2em 0 0.2em; }}
section > p {{ margin: 0.2em 0 0.8em; opacity: 0.75; font-size: 0.9em;
       max-width: 55em; }}
.host[style] {{ outline: 1px dashed currentColor; outline-offset: 4px; }}
{sheet}
</style>
<script>{iife}</script>
</head>
<body>
<h1>greater_tables — demo 2</h1>
<p>TeX cells, long-text wrapping (both Fabricator generators), wide-range
floats in engineering format, and the csv-grid width solver in both modes.
Regenerated by <code>tests/make_goldens.py</code>.</p>
{chr(10).join(sections)}
<script>
document.querySelectorAll('script.gt-doc').forEach(s => {{
    const host = s.nextElementSibling;
    if (s.dataset.width) host.style.width = s.dataset.width + 'px';
    const doc = JSON.parse(s.textContent);
    GtRender.renderTable(doc, {{ mount: host, allowHtml: true,
                                 fit: s.dataset.fit || undefined }});
}});
</script>
<script defer src="https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-chtml.js"></script>
</body>
</html>
'''
    path = ROOT / 'demo2.html'
    path.write_text(page, encoding='utf-8', newline='\n')
    return path


