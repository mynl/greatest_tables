"""THE conformance test: Python HTML must byte-match the walker's transcripts.

Both renderers walk the same golden IR files; the committed JSONL transcripts
(generated by node + linkedom from gt-render.js) are the contract. A failure
here means the two renderers disagree about structure, classes, or text.
"""

from pathlib import Path

import pytest

from greatest_tables import TableDoc

from transcribe import transcribe

IR = Path(__file__).parent / 'golden' / 'ir'
TRANSCRIPT = Path(__file__).parent / 'golden' / 'transcript'

NAMES = sorted(p.stem for p in IR.glob('*.json'))


def test_have_goldens():
    assert NAMES and all((TRANSCRIPT / f'{n}.jsonl').exists() for n in NAMES)


@pytest.mark.parametrize('name', NAMES)
def test_python_matches_walker(name):
    doc = TableDoc.read((IR / f'{name}.json').read_bytes())
    ours = transcribe(doc).encode('utf-8')
    theirs = (TRANSCRIPT / f'{name}.jsonl').read_bytes()
    assert ours == theirs, f'{name}: python HTML disagrees with walker'
