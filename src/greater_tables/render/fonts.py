def face(name: str) -> Face:
    """The face called ``name``; a ``ValueError`` lists the known names."""
    try:
        return FACES[name]
    except KeyError:
        raise ValueError(f'unknown tikz_font {name!r}; known faces: '
                         f'{", ".join(FACES)}') from None
