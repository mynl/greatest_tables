"""Glyph advance widths for the faces a TikZ table may be set in.

TeX needs a table's column widths before it sets the table, so the TikZ
layout estimates each cell's width from a per-glyph table. The estimate is
only as good as the match between the table and the face the document uses:
STIX Two sets lowercase about 5% wider than Times and Lato its digits 14%
wider, so a column sized in Times metrics wraps a label set in either.
``HouseStyle.tikz_font`` names the face; HTML is unaffected, because the
browser measures.

Each face holds two tables, roman and bold, as **integer milli-ems** (0.444em
is 444; see ``textlength``'s module docstring for why integers). Headers and
the cells of total rows set bold, and the bold/roman ratio differs by glyph:
digits are usually the same width, lowercase letters up to 15% wider, so one
widening factor either pads every number or leaves words short.

Every table was measured in TeX, not typed, with
``dev/tools/measure_glyphs.py``, which also lists the font file each face was
measured from and checks a face against whole cells of the fixture corpus.
A glyph a table lacks takes ``DEFAULT_WIDTH``. Mathematics is not here:
``textlength.math_milli`` token-counts it and prices letters from the face.
"""

