HEADER = """---
title: greater_tables examples ({n} tables)
author: generated by dev/tools/make_example_qmd.py
date: '{date}'
number-sections: false
format:
  html:
    theme: cosmo
    toc: true
    code-tools: true
    code-fold: true
    embed-resources: true
    html-math-method: mathjax
  pdf:
    documentclass: article
    papersize: a4
    fontsize: 10pt
    keep-tex: true
    geometry: margin=1in
    toc: false
    pdf-engine: tectonic
    include-in-header:
      text: |
        \\usepackage{{tikz}}
        \\usetikzlibrary{{arrows,calc,positioning,matrix,shapes.geometric,backgrounds,fit}}
        {tikz_preamble}
---

Fabricator-generated showcase for the greater_tables engine: each block is
the blog pattern — a python cell ending in `GT(df, ...)`. Math cells such as
$\\psi(u) = \\Pr(U_t < 0)$ typeset via MathJax in HTML (this sentence's
inline math makes Quarto load it) and natively in PDF.

```{{python}}
#| echo: true
#| code-fold: true
import pandas as pd
from greater_tables import GT, Fabricator
```
"""

BLOCK = """
## {title}

```{{python}}
#| echo: true
#| code-fold: true
{body}
GT(df, caption='{caption}'{extra})
```
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('-n', type=int, default=10, help='number of tables')
    ap.add_argument('--out', default='c:/tmp', help='output directory')
    args = ap.parse_args()

    today = datetime.date.today().isoformat()
    out = Path(args.out) / f'example-{today}-n-{args.n}.qmd'
    parts = [HEADER.format(n=args.n, date=today,
                           tikz_preamble=TIKZ_PREAMBLE)]
    for i in range(args.n):
        title, caption, body = RECIPES[i % len(RECIPES)]
        seed = 1000 + i
        body = body.format(s=seed)
        extra = ', **spec' if 'spec = ' in body else ''
        suffix = '' if i < len(RECIPES) else f' (variant {i // len(RECIPES) + 1})'
        parts.append(BLOCK.format(title=title + suffix, body=body,
                                  caption=caption.replace("'", r"\'"),
                                  extra=extra))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(''.join(parts), encoding='utf-8', newline='\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
