"""Generate a Quarto example file: n Fabricator tables rendered via GT.

Blog-pattern blocks — a python cell whose last line is ``GT(df, ...)`` —
against the greater_tables facade, with a self-contained PDF preamble
(TikZ + the \\I strut) so the file renders anywhere, both formats:

    uv run python dev/tools/make_example_qmd.py [-n 10] [--out c:/tmp]

Then render (quarto must use the GT2 venv python until the package is
published — set QUARTO_PYTHON):

    $env:QUARTO_PYTHON = 'V:/dev/greatest-tables/.venv/Scripts/python.exe'
    quarto render c:/tmp/example-YYYY-MM-DD-n-10.qmd

Output lands next to the qmd. Header modeled on the ConvexConsiderations
blog setup (html: cosmo/code-fold; pdf: article/a4/tectonic).
"""

